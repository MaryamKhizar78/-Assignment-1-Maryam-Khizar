import json

FILE_NAME = "tasks.json"
tasks = []


# Load tasks from JSON file
def load_tasks():
    global tasks

    try:
        with open(FILE_NAME, "r") as file:
            tasks = json.load(file)

        print("Tasks loaded successfully.")

    except FileNotFoundError:
        tasks = []
        print("No saved tasks found. Starting with an empty list.")

    except json.JSONDecodeError:
        tasks = []
        print("JSON file is invalid. Starting with an empty list.")


# Save tasks to JSON file
def save_tasks():
    with open(FILE_NAME, "w") as file:
        json.dump(tasks, file, indent=4)


# Add a new task
def add_task():
    title = input("Enter task title: ").strip()

    if title == "":
        print("Task title cannot be empty.")
        return

    task = {"title": title, "done": False}
    tasks.append(task)

    save_tasks()
    print("Task added successfully.")


# View all tasks
def view_tasks():
    if len(tasks) == 0:
        print("No tasks available.")
        return

    print("\n--- YOUR TASKS ---")

    for i, task in enumerate(tasks, start=1):
        if task["done"]:
            status = "Done"
        else:
            status = "Pending"

        print(f"{i}. {task['title']} [{status}]")


# Complete a task
def complete_task():
    view_tasks()

    if len(tasks) == 0:
        return

    try:
        number = int(input("Enter task number to complete: "))

        if number < 1 or number > len(tasks):
            print("Invalid task number.")
            return

        tasks[number - 1]["done"] = True

        save_tasks()
        print("Task completed successfully.")

    except ValueError:
        print("Please enter a valid number.")


# Delete a task
def delete_task():
    view_tasks()

    if len(tasks) == 0:
        return

    try:
        number = int(input("Enter task number to delete: "))

        if number < 1 or number > len(tasks):
            print("Invalid task number.")
            return

        removed_task = tasks.pop(number - 1)

        save_tasks()
        print(f"Task '{removed_task['title']}' deleted successfully.")

    except ValueError:
        print("Please enter a valid number.")


# Main menu
def main():
    load_tasks()

    while True:
        print("\n--- TASK TRACKER ---")
        print("1. Add")
        print("2. View")
        print("3. Complete")
        print("4. Delete")
        print("5. Exit")

        choice = input("Enter your choice: ").strip()

        if choice == "1":
            add_task()

        elif choice == "2":
            view_tasks()

        elif choice == "3":
            complete_task()

        elif choice == "4":
            delete_task()

        elif choice == "5":
            save_tasks()
            print("Tasks saved. Goodbye!")
            break

        else:
            print("Invalid menu choice. Please select 1 to 5.")


# Run the program
if __name__ == "__main__":
    main()